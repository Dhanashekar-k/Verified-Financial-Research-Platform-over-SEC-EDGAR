"""Write docs/milestones/M03-report.md from the M3 result files only (hard rule 1).

    python -m scripts.make_m03_report

Inputs, all under docs/milestones/: M03-embed-metrics.json (stage A), M03-export-metrics.json
(stage B), M03-serving-load.json, M03-serving-swap.json, M03-serving-bench.json and
M03-spend.json (stages C and D). A missing file or key is printed as NOT MEASURED, never filled in.
"""

# ruff: noqa: E501 - the report lines are long f-strings; line length is not the point here

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

DIR = Path("docs/milestones")
NM = "NOT MEASURED"


def load(name: str) -> dict[str, Any]:
    path = DIR / name
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def get(d: Any, *keys: str, default: Any = None) -> Any:
    for k in keys:
        if isinstance(d, dict) and k in d:
            d = d[k]
        else:
            return default
    return d


def f(value: Any, fmt: str = "{:,}", suffix: str = "") -> str:
    if value is None:
        return NM
    try:
        return fmt.format(value) + suffix
    except (ValueError, TypeError):
        return str(value)


def ms(value: Any) -> str:
    return NM if value is None else f"{value:.1f} ms"


def mins(seconds: Any) -> str:
    return NM if seconds is None else f"{seconds / 60:.1f} min"


def build() -> str:
    emb, exp = load("M03-embed-metrics.json"), load("M03-export-metrics.json")
    ld, swp = load("M03-serving-load.json"), load("M03-serving-swap.json")
    bench, spend = load("M03-serving-bench.json"), load("M03-spend.json")
    served = emb.get("served_run", {})
    dod = served.get("dod_athena_2026-11-22", {})
    t2b = served.get("t2b_measured", {})
    lr = ld.get("load_report", {})
    secs = lr.get("seconds", {})
    curve = bench.get("hnsw_curve", {})
    chosen = get(bench, "chosen_default_ef_search")
    L: list[str] = []
    a = L.append

    a("# M3 report: embeddings and the serving store")
    a("")
    a(
        "Generated by `scripts/make_m03_report.py` from the JSON files under `docs/milestones/`; no number is typed by hand."
    )
    a(
        "Latency and index-build times on the serving box are **PRELIMINARY**: it is a Free-plan `m7i-flex.large`, and flex instances have a CPU baseline "
        "that can throttle sustained load. M9 re-measures them on the final box. Recall@10 and swap correctness do not depend on speed and stand as the M3 gates."
    )
    a("")
    a("## Definition of done")
    a("")
    a("| Gate | Result | Source |")
    a("|---|---|---|")
    a(
        f"| `chunk_embeddings` complete over the embedded scope (missing = 0) | {f(dod.get('missing_over_embedded_scope'))} missing of {f(dod.get('expected_in_scope_chunks'))} in-scope chunks | M03-embed-metrics.json `served_run.dod_athena_2026-11-22` |"
    )
    a(
        f"| T2b recorded | ${f(t2b.get('usd_per_100k_chunks'), '{:.2f}')} per 100k chunks, {f(t2b.get('chunks_per_minute_whole_runs'), '{:,.0f}')} chunks/min (whole runs) | `served_run.t2b_measured` |"
    )
    a(
        f"| Export corpus_version=1 with manifest; manifest counts = Parquet footers | facts {f(get(exp, 'manifest', 'facts_rows'))}, chunks {f(get(exp, 'manifest', 'chunks_rows'))}, companies {f(get(exp, 'manifest', 'companies_rows'))}; every file's footer matches: {get(exp, 'footer_check_from_laptop_via_pyarrow', 'every_file_matches')} | M03-export-metrics.json |"
    )
    a(
        f"| Idempotent re-export, N = max+1 | same counts/snapshots: {get(exp, 'reexport', 'same_headline_fields')}; one `corpus_versions` row | M03-export-metrics.json `reexport` |"
    )
    a(
        f"| Loader swaps it into Postgres; rollback tested | {f(get(swp, 'reader', 'reads'))} reader queries during {len(swp.get('steps', []))} swap/rollback steps, errors: {f(len(get(swp, 'reader', 'errors', default=[])) if swp else None)} | M03-serving-swap.json |"
    )
    best = max((v.get("recall_at_10", 0) for v in curve.values()), default=None) if curve else None
    a(
        f"| HNSW recall@10 vs exact >= 0.95 at the chosen ef_search | ef_search {f(chosen)}: recall {f(get(curve, str(chosen), 'recall_at_10'), '{:.3f}')} (lower of two query sets); best {f(best, '{:.3f}')} | M03-serving-bench.json `hnsw_curve` |"
    )
    a(
        f"| Numeric lookup p95 < 50 ms (PRELIMINARY) | p50 {ms(get(bench, 'numeric_lookup', 'p50_ms'))}, p95 {ms(get(bench, 'numeric_lookup', 'p95_ms'))} | `numeric_lookup` |"
    )
    a(
        f"| Hybrid p95 < 200 ms, no rerank (PRELIMINARY) | at ef_search {f(chosen)}: p50 {ms(get(bench, 'hybrid', str(chosen), 'total', 'p50_ms'))}, p95 {ms(get(bench, 'hybrid', str(chosen), 'total', 'p95_ms'))} (includes embedding the question on the box) | `hybrid` |"
    )
    a(
        "| Load/swap/rollback integration test green in CI | see the repository's CI run; Testcontainers suites `tests/integration/test_load_snapshot.py` and `test_retrieval_pg.py` | not a JSON result |"
    )
    a("")
    a("## Stage A: embeddings on Glue")
    a("")
    a(
        f"- Embedded: {f(dod.get('rows'))} chunks (10-K, 10-K/A, FinanceBench). dim {f(dod.get('dim_min'))} on every row, norms {f(dod.get('norm_min'), '{:.8f}')} to {f(dod.get('norm_max'), '{:.8f}')}, NaN or inf rows: {f(dod.get('rows_nan_or_inf'))}."
    )
    a(
        f"- Tiny chunks (n_tokens <= 5) embedded in scope: {f(dod.get('tiny_chunks_n_tokens_le_5_embedded'))}; ADR-035 predicted {f(dod.get('adr_035_preflight_prediction'))}."
    )
    a(
        f"- Deliberately not embedded (EDGAR 10-Q and 10-Q/A): {f(dod.get('edgar_html_10q_chunks_not_embedded'))} chunks (ADR-037)."
    )
    a(
        f"- Measured T2b: {f(t2b.get('dpu_hours'), '{:.2f}')} DPU-hours = ${f(t2b.get('cost_usd'), '{:.2f}')} at ${f(t2b.get('rate_usd_per_dpu_hour'), '{:.2f}')}/DPU-hour over {f(t2b.get('chunks'))} chunks. {t2b.get('scope_of_number', '')}"
    )
    a(
        f"- Cross-architecture check (x86 Glue vs arm64): min cosine {f(get(emb, 'cross_arch_agreement', 'local_vs_glue', 'min_cosine'), '{:.7f}')}, none below the 0.9999 gate: {get(emb, 'cross_arch_agreement', 'local_vs_glue', 'passed')}."
    )
    a("")
    a("## Stage B: export")
    a("")
    a(
        f"- `{get(exp, 'export_uri')}`: {f(get(exp, 'files', 'chunks', 'n_files'))} chunk files, {f(get(exp, 'files', 'chunks', 'bytes', default=0) / 1e9 if get(exp, 'files', 'chunks', 'bytes') else None, '{:.2f}')} GB of chunks."
    )
    a(
        f"- Chunks excluded for n_tokens <= 5: {f(get(exp, 'manifest', 'chunk_exclusions', 'count'))}; not embedded (10-Q scope decision): {f(get(exp, 'manifest', 'embedding_scope', 'not_embedded', 'count'))}."
    )
    a(f"- Iceberg snapshots pinned: {json.dumps(get(exp, 'manifest', 'iceberg_snapshots'))}.")
    a(
        f"- Export cost: ${f((get(exp, 'first_run', 'cost_usd') or 0) + (get(exp, 'reexport', 'cost_usd') or 0), '{:.2f}')} for two runs."
    )
    a("")
    a("## Stage C: serving Postgres load (PRELIMINARY timings)")
    a("")
    inst = ld.get("instance", {})
    a(
        f"- Box: {inst.get('type', NM)}, {inst.get('cpu_model', NM)}, {f(inst.get('vcpus'))} vCPUs, {f(inst.get('memory_mib'))} MiB RAM; Postgres {get(ld, 'server', 'postgres', default=NM)}, pgvector {get(ld, 'server', 'pgvector', default=NM)}; image `{get(ld, 'server', 'image_digest', default=NM)}`."
    )
    a("")
    a("| Phase | Seconds |")
    a("|---|---|")
    for k in sorted(secs):
        a(f"| {k} | {f(secs[k], '{:,.1f}')} |")
    a("")
    a("| Object | Size |")
    a("|---|---|")
    for k, v in sorted(lr.get("sizes_bytes", {}).items()):
        a(f"| {k} | {f(v / 1e6, '{:,.0f}', ' MB')} |")
    a("")
    res = ld.get("resources", {})
    a(
        f"- Peak disk used: {f(res.get('peak_disk_used_gb'), '{:.1f}', ' GB')}; minimum available memory {f(res.get('min_mem_available_mib'), '{:,.0f}', ' MiB')}; maximum swap used {f(res.get('max_swap_used_mib'), '{:,.0f}', ' MiB')}."
    )
    a(
        f"- CPU during the load and index build: busy {f(res.get('cpu_busy_fraction_load'), '{:.1%}')}, steal {f(res.get('steal_fraction_load'), '{:.2%}')} of all time, {f(res.get('busy_steal_fraction_load'), '{:.2%}')} of busy time."
    )
    a(f"- Did 8 GiB hold the working set? {ld.get('working_set_verdict', NM)}")
    a(
        f"- NUL characters removed at load: {json.dumps(get(lr, 'validation', 'nul_characters_removed'))}."
    )
    a(
        f"- Server notices during the load (for example the HNSW memory warning): {json.dumps(get(lr, 'validation', 'server_notices'))}."
    )
    a("")
    a("## Stage D: swap correctness on the real tables")
    a("")
    a("| Step | corpus_state (live, previous) | chunks view reads | versioned tables |")
    a("|---|---|---|---|")
    for s in swp.get("steps", []):
        a(
            f"| {s['step']} | {tuple(s['corpus_state'])} | {s['chunks_view_reads']} | {', '.join(s['versioned_tables'])} |"
        )
    a(
        f"\nReader thread: {f(get(swp, 'reader', 'reads'))} reads, errors {json.dumps(get(swp, 'reader', 'errors'))}. {swp.get('note', '')}"
    )
    a("")
    a("## Stage D: retrieval benchmark (latency PRELIMINARY)")
    a("")
    a(
        f"{f(bench.get('queries'))} queries per set; instance {bench.get('instance_type', NM)}; server {get(bench, 'server', 'version', default=NM)}, pgvector {get(bench, 'server', 'pgvector', default=NM)}, {f(get(bench, 'server', 'chunks'))} chunks. Exact search takes {f(bench.get('exact_scan_seconds_per_query'), '{:.2f}', ' s')} per query."
    )
    a("")
    a(
        "| ef_search | recall@10 (lower of two sets) | self-span | mixed-pair | min single query | dense_search p50 | p95 |"
    )
    a("|---|---|---|---|---|---|---|")
    for ef in sorted(curve, key=int):
        c = curve[ef]
        a(
            f"| {ef} | {f(c.get('recall_at_10'), '{:.3f}')} | {f(c.get('recall_self_span'), '{:.3f}')} | {f(c.get('recall_mixed_pair'), '{:.3f}')} | {f(c.get('min_single_query_recall'), '{:.2f}')} | {ms(c.get('p50_ms'))} | {ms(c.get('p95_ms'))} |"
        )
    a("")
    a(
        f"**Chosen default `ef_search` = {f(chosen)}.** {bench.get('chosen_default_justification', NM)}"
    )
    a("")
    a("| ef_search | hybrid total p50 | p95 | embed p50 | lexical p50 | dense p50 | fuse p50 |")
    a("|---|---|---|---|---|---|---|")
    for ef, h in sorted(bench.get("hybrid", {}).items(), key=lambda kv: int(kv[0])):
        a(
            f"| {ef} | {ms(h['total']['p50_ms'])} | {ms(h['total']['p95_ms'])} | {ms(h['embed']['p50_ms'])} | {ms(h['lexical']['p50_ms'])} | {ms(h['dense']['p50_ms'])} | {ms(h['fuse']['p50_ms'])} |"
        )
    a("")
    ab = bench.get("query_instruction_ab", {})
    a(
        "BGE query instruction A/B (reported, not used to choose; ADR-033): "
        f"source chunk in exact top-10 with the instruction {f(get(ab, 'with_instruction', 'source_chunk_in_top10'), '{:.3f}')} vs without {f(get(ab, 'without_instruction', 'source_chunk_in_top10'), '{:.3f}')}; "
        f"MRR@10 {f(get(ab, 'with_instruction', 'mrr_at_10'), '{:.3f}')} vs {f(get(ab, 'without_instruction', 'mrr_at_10'), '{:.3f}')}; top-10 overlap between the variants {f(ab.get('top10_overlap_between_variants'), '{:.3f}')}. {ab.get('caveat', '')}"
    )
    a("")
    fd = bench.get("filtered_dense", {})
    a(
        f"Filtered dense search: {f(fd.get('n'))} queries, minimum rows returned {f(fd.get('min_rows_returned'))} of {f(fd.get('limit'))}; plans using the HNSW index: {fd.get('plans_using_the_hnsw_index', NM)}."
    )
    a(
        f"\nCPU steal over the whole bench: {f(bench.get('cpu_steal_fraction_whole_run'), '{:.2%}')} of all time, {f(bench.get('cpu_steal_fraction_of_busy_time'), '{:.2%}')} of busy time."
    )
    a("")
    a("## Spend")
    a("")
    a("| Item | USD |")
    a("|---|---|")
    for item in spend.get("items", []):
        a(f"| {item['item']} | {f(item['usd'], '{:.2f}')} |")
    a(f"| **Total M3** | **{f(spend.get('total_m3_usd'), '{:.2f}')}** |")
    a("")
    a(spend.get("reconciliation", ""))
    a("")
    return "\n".join(L) + "\n"


def main() -> int:
    out = DIR / "M03-report.md"
    out.write_text(build(), encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
