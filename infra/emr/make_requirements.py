"""Regenerate `requirements-emr.txt`: the executors' Python dependencies, pinned.

    uv run python infra/emr/make_requirements.py

The executors import `pipelines.spark.*` (pandas, pyarrow, pydantic, the parsing library), so they
need these packages and their transitive closure at the versions in `uv.lock` (the environment is
synced to the lock). PySpark itself comes from the EMR release. `setuptools` supplies the
`distutils` shim PySpark 3.5's `pandas_udf` needs on Python 3.12.
"""

from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

TOP_LEVEL = [
    "pydantic", "selectolax", "tokenizers", "pymupdf", "pandas", "pyarrow", "numpy", "setuptools",
]  # fmt: skip
OUT = Path(__file__).with_name("requirements-emr.txt")


def closure(names: list[str]) -> dict[str, str]:
    pins: dict[str, str] = {}
    todo = list(names)
    while todo:
        name = todo.pop()
        key = re.sub(r"[-_.]+", "-", name).lower()
        if key in pins:
            continue
        dist = metadata.distribution(name)
        pins[key] = dist.version
        for raw in dist.requires or []:
            req = Requirement(raw)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                todo.append(req.name)
    return pins


def render(pins: dict[str, str]) -> str:
    header = (
        "# Generated by infra/emr/make_requirements.py from the synced environment (uv.lock).\n"
        "# Do not edit by hand; a test fails if a pin drifts from the lock.\n"
    )
    return header + "".join(f"{k}=={v}\n" for k, v in sorted(pins.items()))


def main() -> int:
    OUT.write_text(render(closure(TOP_LEVEL)), encoding="utf-8")
    print(f"wrote {OUT} ({len(closure(TOP_LEVEL))} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
